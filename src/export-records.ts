import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { getPayload } from 'payload'
import config from '@payload-config'
import type { Media, Product as PayloadProduct, SiteSetting } from '@/payload-types'
import type { Picture } from './content/types'
import { getDatabaseUrl, useLiveDatabase } from './lib/database-url'

const outPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), 'content/records.ts')

function tsString(value: string) {
  return JSON.stringify(value)
}

function tsStringArray(values: string[], indent: string) {
  if (values.length === 0) return '[]'
  if (values.length === 1) return `[${tsString(values[0])}]`
  return `[\n${values.map((v) => `${indent}  ${tsString(v)},`).join('\n')}\n${indent}]`
}

function mediaToPicture(media: number | Media | null | undefined): Picture | null {
  if (!media || typeof media === 'number') return null
  const alt = media.alt || media.filename || ''
  if (media.filename) {
    return { src: `/media/${media.filename}`, alt }
  }
  if (media.url) {
    try {
      const u = new URL(media.url, 'http://local')
      if (u.pathname.startsWith('/api/media/file/')) {
        return { src: `/media/${path.basename(u.pathname)}`, alt }
      }
      if (u.pathname.startsWith('/media/')) {
        return { src: u.pathname, alt }
      }
    } catch {
      /* relative url */
    }
    if (media.url.startsWith('/')) return { src: media.url, alt }
  }
  return media.url ? { src: media.url, alt } : null
}

function pictures(values: (number | Media)[] | null | undefined): Picture[] {
  return (values ?? []).map(mediaToPicture).filter((p): p is Picture => p !== null)
}

function emitPicture(p: Picture, indent: string) {
  return `{ src: ${tsString(p.src)}, alt: ${tsString(p.alt)} }`
}

function emitSettings(doc: SiteSetting): string {
  const hero = pictures(doc.hero)
  const editorial = mediaToPicture(doc.editorialImage)
  const emails = (doc.emails ?? [])
    .filter((e) => e.label && e.address)
    .map((e) => `{ label: ${tsString(e.label as string)}, address: ${tsString(e.address as string)} }`)
  const navLinks = (doc.navLinks ?? [])
    .filter((l) => l.label && l.href)
    .map((l) => `{ label: ${tsString(l.label as string)}, href: ${tsString(l.href as string)} }`)

  const menuPdf = doc.menuPdfUrl || ''
  const bookUrl = doc.bookUrl || ''

  return `export const MENU_PDF_URL = ${tsString(menuPdf)}
export const BOOK_URL = ${tsString(bookUrl)}

export const settings: SiteSettings = {
  tagline: ${tsString(doc.tagline || '')},
  copyright: ${tsString(doc.copyright || '')},
  socialHandle: ${tsString(doc.socialHandle || '')},
  socialUrl: ${tsString(doc.socialUrl || '')},
  statement: ${tsString(doc.statement || '')},
  contactIntro: ${tsString(doc.contactIntro || '')},
  contactPhone: ${tsString(doc.contactPhone || '')},
  contactPhoneHours: ${tsString(doc.contactPhoneHours || '')},
  menuPdfUrl: MENU_PDF_URL,
  bookUrl: BOOK_URL,
  emails: [
${emails.map((e) => `    ${e},`).join('\n')}
  ],
  hero: [
${hero.map((h) => `    ${emitPicture(h, '    ')},`).join('\n')}
  ],
  originKicker: ${tsString(doc.originKicker || '')},
  originPlace: ${tsString(doc.originPlace || '')},
  storeAddress: ${tsString(doc.storeAddress || '')},
  instagramLabel: ${tsString(doc.instagramLabel || '')},
  editorialImage: ${editorial ? emitPicture(editorial, '') : 'null'},
  navLinks: [
${navLinks.map((l) => `    ${l},`).join('\n')}
  ],
}`
}

function emitProduct(doc: PayloadProduct): string {
  const gallery = pictures(doc.gallery)
  const image = mediaToPicture(doc.image) ?? gallery[0]
  if (!image) {
    throw new Error(`Product "${doc.slug}" has no image — add media in /admin before export.`)
  }
  const galleryOut = gallery.length ? gallery : [image]
  const sizes = (doc.sizes ?? []) as string[]

  return `  {
    title: ${tsString(doc.title)},
    slug: ${tsString(doc.slug)},
    price: ${doc.price ?? 0},
    description: ${tsString(doc.description || '')},
    sizes: ${tsStringArray(sizes, '  ')},
    image: ${emitPicture(image, '    ')},
    gallery: [
${galleryOut.map((g) => `      ${emitPicture(g, '      ')},`).join('\n')}
    ],
    active: ${doc.active ? 'true' : 'false'},
    order: ${doc.order ?? 0},
  }`
}

const payload = await getPayload({ config })
const settingsDoc = await payload.findGlobal({ slug: 'site-settings', depth: 1 })
const productsResult = await payload.find({
  collection: 'products',
  sort: 'order',
  limit: 200,
  depth: 1,
})

const source = useLiveDatabase() ? 'Railway (live)' : 'local Postgres'
const dbHint = getDatabaseUrl().replace(/:[^:@/]+@/, ':***@')

const file = `import type { Product, SiteSettings } from './types'

/** Generated by \`npm run export:records\` from ${source} at ${new Date().toISOString()}. */
/** DB: ${dbHint} */
/** Overwrites this file — commit if you want Vercel static preview to match CMS. */

${emitSettings(settingsDoc)}

type SeedProduct = Omit<Product, 'id' | 'stripeProductId' | 'stripePriceId'> & {
  image: { src: string; alt: string }
  gallery?: { src: string; alt: string }[]
}

export const products: SeedProduct[] = [
${productsResult.docs.map(emitProduct).join(',\n')}
]
`

fs.writeFileSync(outPath, file, 'utf8')
console.log(`Wrote ${outPath}`)
console.log(`  Settings + ${productsResult.docs.length} product(s) from ${source}`)
console.log('  Commit and push to refresh Vercel static preview (GABOS_STATIC_PREVIEW=true).')
process.exit(0)
